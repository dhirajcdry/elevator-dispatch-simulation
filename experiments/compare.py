"""Run every method combination on every traffic type and write experiments/results.md.

    python3 experiments/compare.py

Two buildings, 10 traffic types, 9 combinations (3 elevator assignments x 3 service
orders, allowed delay 80), 5 seeds each. Each number is the mean over the 5 seeds.
"""

import os
import statistics
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))  # the project folder, for simulate

from main import percentile_95
from simulation import simulate
from traffic import TRAFFIC, make_requests

BUILDINGS = {
    '30-floor building (30 floors, 4 elevators, capacity 4)': (30, 4, 4),
    'Default building (100 floors, 4 elevators, capacity 10)': (100, 4, 10),
}
COMBINATIONS = [
    (assignment, service_order)
    for assignment in ['round-robin', 'nearest', 'forecast']
    for service_order in ['request', 'direction', 'forecast']
]
SEEDS = range(5)
MEASURES = {
    'Average total time': lambda passengers: statistics.mean(p.total_time for p in passengers),
    '95th percentile total time': lambda passengers: percentile_95([p.total_time for p in passengers]),
    'Longest wait': lambda passengers: max(p.wait_time for p in passengers),
}


def main() -> None:
    lines = ['# Results', '', 'Generated by `python3 experiments/compare.py`. Times are in ticks, '
             'each the mean over 5 seeds. Rows: elevator assignment / service order. '
             'Allowed delay 80 for the forecast service order.', '']
    lines += ['Traffic types (from experiments/traffic.py):', '']
    for traffic, description in TRAFFIC.items():
        lines.append(f'- `{traffic}`: {description}')
    lines.append('')

    for building, (floors, elevators, capacity) in BUILDINGS.items():
        results = {}  # (assignment, service order, traffic) -> {measure: mean over seeds}
        for assignment, service_order in COMBINATIONS:
            started = time.perf_counter()
            for traffic in TRAFFIC:
                values = {measure: [] for measure in MEASURES}
                for seed in SEEDS:
                    requests = make_requests(traffic, floors, elevators, seed)
                    _, passengers = simulate(requests, floors, elevators, capacity, assignment, service_order)
                    for measure, calculate in MEASURES.items():
                        values[measure].append(calculate(passengers))
                results[(assignment, service_order, traffic)] = {
                    measure: statistics.mean(seed_values) for measure, seed_values in values.items()
                }
            print(f'{floors} floors, {assignment} / {service_order}: {time.perf_counter() - started:.1f} s')

        lines += [f'## {building}', '']
        for measure in MEASURES:
            lines += [f'### {measure}', '']
            lines.append('| | ' + ' | '.join(TRAFFIC) + ' |')
            lines.append('| --- |' + ' ---: |' * len(TRAFFIC))
            for assignment, service_order in COMBINATIONS:
                cells = [f'{results[(assignment, service_order, traffic)][measure]:.0f}' for traffic in TRAFFIC]
                lines.append(f'| {assignment} / {service_order} | ' + ' | '.join(cells) + ' |')
            lines.append('')

    with open(os.path.join(HERE, 'results.md'), 'w') as file:
        file.write('\n'.join(lines))
    print('Written to experiments/results.md')


if __name__ == '__main__':
    main()
